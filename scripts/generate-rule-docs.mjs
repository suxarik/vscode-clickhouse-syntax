#!/usr/bin/env node
/**
 * Regenerate docs/rules.md from the rule registry, so the reference the
 * diagnostics link to cannot drift from the rules that actually run.
 *
 * Reads the compiled output, so run `npm run compile` first (npm run docs:rules
 * does that for you).
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const { RULES } = require(join(ROOT, 'out', 'lint', 'rules.js'));

const SEVERITY_LABEL = {
    error: 'Error',
    warning: 'Warning',
    info: 'Information',
    hint: 'Hint',
    off: 'Off',
};

const lines = [
    '# ClickHouse lint rules',
    '',
    '<!-- GENERATED by scripts/generate-rule-docs.mjs — do not edit by hand. -->',
    '',
    'Every diagnostic this extension reports carries a rule id. Set a severity per rule:',
    '',
    '```jsonc',
    '"clickhouse.diagnostics.rules": {',
    '  "select-star": "off",',
    '  "unknown-column": "error"',
    '}',
    '```',
    '',
    'Valid severities are `off`, `hint`, `info`, `warning` and `error`.',
    '',
    '## Silencing a rule inline',
    '',
    '```sql',
    '-- ch-lint-disable-next-line select-star',
    'SELECT * FROM events;',
    '',
    'SELECT * FROM events; -- ch-lint-disable-line select-star',
    '',
    '-- ch-lint-disable unknown-table, missing-final',
    '-- … queries …',
    '-- ch-lint-enable unknown-table',
    '```',
    '',
    'A directive with no rule names applies to every rule. `ch-lint-disable` without a',
    'matching `ch-lint-enable` runs to the end of the file.',
    '',
    '## Rules',
    '',
    '| Rule | Default | What it catches |',
    '|---|---|---|',
];

for (const rule of [...RULES].sort((a, b) => a.id.localeCompare(b.id))) {
    lines.push(`| [\`${rule.id}\`](#${rule.id}) | ${SEVERITY_LABEL[rule.defaultSeverity]} | ${rule.description} |`);
}
lines.push('');

for (const rule of [...RULES].sort((a, b) => a.id.localeCompare(b.id))) {
    lines.push(`### ${rule.id}`);
    lines.push('');
    lines.push(rule.description);
    lines.push('');
    lines.push(`Default severity: **${SEVERITY_LABEL[rule.defaultSeverity]}**`);
    lines.push('');
}

mkdirSync(join(ROOT, 'docs'), { recursive: true });
writeFileSync(join(ROOT, 'docs', 'rules.md'), `${lines.join('\n')}`, 'utf8');
console.log(`docs/rules.md written with ${RULES.length} rules`);
